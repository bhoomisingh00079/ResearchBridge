"""Member B project-workspace primitives.

This module is deliberately independent of the shared ORM and authentication
setup. Routers can inject the current user's project membership and persist the
returned metadata through the application repositories.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date, datetime, timezone
from pathlib import Path
from typing import Iterable, Protocol
import mimetypes
import secrets


MILESTONE_STATUSES = {"Not Started", "In Progress", "Completed", "Blocked"}
TASK_STATUSES = MILESTONE_STATUSES
RESOURCE_TYPES = {"Paper", "Dataset", "Link", "File"}
DEFAULT_RESOURCE_MIME_TYPES = {
    "application/pdf",
    "text/plain",
    "text/csv",
    "application/zip",
    "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
    "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
}


class WorkspaceError(ValueError):
    """A caller supplied invalid project-workspace data."""


class PrivateStorage(Protocol):
    def put(self, filename: str, content: bytes, content_type: str | None = None) -> str: ...
    def get(self, reference: str) -> bytes: ...
    def delete(self, reference: str) -> None: ...


class LocalPrivateStorage:
    """Opaque-key file storage rooted outside the public web directory."""

    def __init__(
        self,
        root: str | Path,
        *,
        max_bytes: int = 20 * 1024 * 1024,
        allowed_types: Iterable[str] = DEFAULT_RESOURCE_MIME_TYPES,
    ) -> None:
        if max_bytes < 1:
            raise ValueError("max_bytes must be positive")
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)
        self.max_bytes = max_bytes
        self.allowed_types = frozenset(allowed_types)

    def put(self, filename: str, content: bytes, content_type: str | None = None) -> str:
        if not filename or Path(filename).name != filename or "\x00" in filename:
            raise WorkspaceError("Invalid filename")
        if Path(filename).suffix.lower() not in {".pdf", ".txt", ".csv", ".zip", ".docx", ".xlsx"}:
            raise WorkspaceError("File extension is not allowed")
        if len(content) > self.max_bytes:
            raise WorkspaceError("File exceeds the configured size limit")
        guessed = mimetypes.guess_type(filename)[0]
        detected = content_type or guessed or "application/octet-stream"
        if guessed and guessed != detected:
            raise WorkspaceError("Filename extension and content type do not match")
        if detected not in self.allowed_types:
            raise WorkspaceError("File type is not allowed")
        if detected == "application/pdf" and not content.startswith(b"%PDF-"):
            raise WorkspaceError("File contents do not match the declared PDF type")
        if detected in {"application/zip", "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
                        "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"} and not content.startswith(b"PK"):
            raise WorkspaceError("File contents do not match the declared archive type")
        if detected in {"text/plain", "text/csv"} and b"\x00" in content:
            raise WorkspaceError("Text files cannot contain null bytes")
        reference = secrets.token_urlsafe(32)
        target = self._path(reference)
        target.write_bytes(content)
        return reference

    def get(self, reference: str) -> bytes:
        return self._path(reference).read_bytes()

    def delete(self, reference: str) -> None:
        self._path(reference).unlink(missing_ok=True)

    def _path(self, reference: str) -> Path:
        # References are generated by token_urlsafe; reject path syntax before
        # resolving to ensure a corrupted DB value cannot escape the private root.
        if not reference or any(ch not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_" for ch in reference):
            raise WorkspaceError("Invalid storage reference")
        candidate = (self.root / reference).resolve()
        if candidate.parent != self.root:
            raise WorkspaceError("Invalid storage reference")
        return candidate


@dataclass(frozen=True)
class ResourceMetadata:
    project_id: int
    title: str
    description: str
    type: str
    storage_reference: str | None
    uploaded_by: int
    created_at: datetime
    link_url: str | None = None

    def __post_init__(self) -> None:
        if self.type not in RESOURCE_TYPES:
            raise WorkspaceError("Unsupported resource type")
        if self.type == "File" and not self.storage_reference:
            raise WorkspaceError("File resources require private storage")
        if self.type == "Link" and not self.link_url:
            raise WorkspaceError("Link resources require a URL")


@dataclass(frozen=True)
class ActivityEntry:
    id: int
    actor_user_id: int | None
    entity_type: str
    entity_id: int
    project_id: int | None
    action: str
    timestamp: datetime


def is_overdue(target_date: date, status: str, *, today: date | None = None) -> bool:
    """Shared FR-020 rule: due date is before today and work is incomplete."""
    if status not in MILESTONE_STATUSES:
        raise WorkspaceError("Unsupported milestone status")
    return status != "Completed" and target_date < (today or date.today())


def validate_status_transition(current: str, requested: str) -> str:
    """Validate workspace status values while allowing explicit recovery paths."""
    if current not in MILESTONE_STATUSES or requested not in MILESTONE_STATUSES:
        raise WorkspaceError("Unsupported status")
    allowed = {
        "Not Started": {"Not Started", "In Progress", "Blocked", "Completed"},
        "In Progress": {"In Progress", "Blocked", "Completed", "Not Started"},
        "Blocked": {"Blocked", "In Progress", "Completed", "Not Started"},
        "Completed": {"Completed", "In Progress"},
    }
    if requested not in allowed[current]:
        raise WorkspaceError(f"Cannot change status from {current} to {requested}")
    return requested


def paginate_activity(
    entries: Iterable[ActivityEntry], *, page: int = 1, page_size: int = 20
) -> list[ActivityEntry]:
    if page < 1 or page_size < 1 or page_size > 100:
        raise WorkspaceError("page must be positive and page_size must be between 1 and 100")
    ordered = sorted(entries, key=lambda item: (item.timestamp, item.id), reverse=True)
    start = (page - 1) * page_size
    return ordered[start : start + page_size]


def utc_now() -> datetime:
    return datetime.now(timezone.utc)
